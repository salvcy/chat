/**
 * Regenerate `schema-auth.sql` from the auth config the Worker actually runs.
 *
 *   node gen-schema.mjs > schema-auth.sql
 *
 * This exists because the standalone `@better-auth/cli` is deprecated and
 * npx resolved it to 1.4.21 while the runtime here is 1.7.1. The two
 * disagreed about the `account` table — the CLI omitted `issuer` — and the
 * result was a 500 on every signup with a SQLITE_ERROR buried in the logs.
 *
 * Reading the schema out of the installed library, through the same
 * `createAuth` the Worker calls, makes that class of drift impossible: there
 * is one definition and the SQL is derived from it.
 *
 * Node 24 strips TypeScript types natively, so importing the .ts config
 * needs no build step.
 */
import { DatabaseSync } from "node:sqlite";
import { getSchema } from "./node_modules/better-auth/dist/db/get-schema.mjs";
import { createAuth } from "./src/auth.ts";

const auth = createAuth(
  {
    DB: new DatabaseSync(":memory:"),
    AUTH_SECRET: "schema-generation-only-not-a-real-secret",
    GOOGLE_CLIENT_ID: "schema-generation-only",
    GOOGLE_CLIENT_SECRET: "schema-generation-only",
    DATA_KEY: "schema-generation-only",
  },
  "https://chat.belayet.co",
);

const sqlType = (f) =>
  f.type === "number" || f.type === "boolean"
    ? "integer"
    : f.type === "date"
      ? "date"
      : "text";

const lines = [
  "-- GENERATED by gen-schema.mjs from src/auth.ts. Do not hand-edit.",
  "-- Regenerate after changing auth options or upgrading better-auth.",
  "",
];

for (const [table, def] of Object.entries(getSchema(auth.options))) {
  const model = def.modelName || table;
  const cols = ['"id" text not null primary key'];
  const indexes = [];
  for (const [name, f] of Object.entries(def.fields)) {
    const col = f.fieldName || name;
    let s = `"${col}" ${sqlType(f)}`;
    if (f.required !== false) s += " not null";
    if (f.unique) s += " unique";
    if (f.references) {
      s += ` references "${f.references.model}" ("${f.references.field}") on delete ${f.references.onDelete || "cascade"}`;
      indexes.push(
        `CREATE INDEX IF NOT EXISTS "${model}_${col}_idx" ON "${model}" ("${col}");`,
      );
    }
    cols.push(s);
  }
  lines.push(
    `CREATE TABLE IF NOT EXISTS "${model}" (${cols.join(", ")});`,
    ...indexes,
    "",
  );
}

console.log(lines.join("\n"));
